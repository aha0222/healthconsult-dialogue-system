# 分数尺度总说明，人工与模型共用
SCALE_NOTE = """**5 分** = 该维度上「找不到任何可改进之处」。这是罕见分数。
给出 5 分时，你必须能说清"为什么连改都无从改起"。说不清，就是 4 分或更低。
**4 分** = 整体到位，但你能明确指出一处可以更好的地方。
**3 分** = 达标但平庸，能指出明显可改进之处。多数合格回复应落在这里。
不要因为"挑不出大错"就给高分——挑不出大错，只说明它不是 1-2 分。"""


def render_dimensions_text() -> str:
    """给大模型评委用的量表文本。"""
    blocks = []
    for name, d in DIMENSIONS.items():
        anchors = "\n".join(f"    {k} 分：{v}" for k, v in sorted(d["anchors"].items()))
        blocks.append(f"【{name}】{d['desc']}\n{anchors}")
    return "\n\n".join(blocks)


def anchors_compact(name: str) -> str:
    """给人工评审页用的紧凑锚点（只显示 1/3/5）。"""
    a = DIMENSIONS[name]["anchors"]
    return f"1分 {a[1]}　|　3分 {a[3]}　|　5分 {a[5]}"


